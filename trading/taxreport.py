"""Tax report for crypto trades (ESTIMATE for Spanish tax return / IRPF, not tax advice).

FIFO method per asset, as required by Spanish tax authority for homogeneous securities. All in euros:
prices in USD/USDC are converted using EURUSD of the day (Yahoo Finance). Fees add to acquisition
value and subtract from disposal value. Output: one row per sale with dates, amounts and gain/loss, ready for CSV export.
"""
from __future__ import annotations

import csv
import io
from collections import defaultdict, deque


def fifo(trades: list[dict], eurusd: dict[str, float] | None = None) -> list[dict]:
    """trades: {date 'YYYY-MM-DD', asset, side 'buy'|'sell', qty, price_usd, fee_usd}. Returns sales with gain in €."""
    eurusd = eurusd or {}
    last = [1.0]

    def rate(day: str) -> float:
        r = eurusd.get(day)
        if r:
            last[0] = r
        return r or last[0]

    lots: dict[str, deque] = defaultdict(deque)
    out = []
    for t in sorted(trades, key=lambda x: x["date"]):
        fx = rate(t["date"])
        qty, px, fee = float(t["qty"]), float(t["price_usd"]), float(t.get("fee_usd", 0))
        if t["side"] == "buy":
            lots[t["asset"]].append([qty, (qty * px + fee) / fx / qty, t["date"]])  # unit cost in € with fee
            continue
        left, cost, first = qty, 0.0, None
        while left > 1e-12 and lots[t["asset"]]:
            lot = lots[t["asset"]][0]
            take = min(left, lot[0])
            cost += take * lot[1]
            first = first or lot[2]
            lot[0] -= take
            left -= take
            if lot[0] <= 1e-12:
                lots[t["asset"]].popleft()
        if left > 1e-9:
            raise ValueError(f"sale of {t['asset']} without sufficient prior purchases ({left} without origin)")
        proceeds = (qty * px - fee) / fx
        out.append({"fecha_venta": t["date"], "activo": t["asset"], "cantidad": round(qty, 10), "fecha_adquisicion": first,
                    "valor_adquisicion_eur": round(cost, 2), "valor_transmision_eur": round(proceeds, 2),
                    "ganancia_eur": round(proceeds - cost, 2)})
    return out


def to_csv(rows: list[dict]) -> str:
    buf = io.StringIO()
    if rows:
        w = csv.DictWriter(buf, fieldnames=list(rows[0]), delimiter=";")
        w.writeheader()
        w.writerows(rows)
    buf.write("\nEstimate generated by Cage using the FIFO method. Review it before filing; this is not tax advice.\n")
    return buf.getvalue()
